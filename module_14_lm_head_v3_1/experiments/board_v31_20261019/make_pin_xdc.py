"""Generate the PL DDR4 pin constraints for lm_head v3.1.

Source of truth: AXU9EGB user manual, section 2.3, table "PL 端 DDR4 SDRAM
引脚分配" (page 16-18).  The table is transcribed verbatim below; no pin is
invented.  PL_DDR4_RST is mapped to AM5 on manual page 18.
"""
from pathlib import Path

# manual net name -> package pin
PINS = {
    # data strobes (differential): _P is the true/t pin, _N the complement/c pin
    "DQS0_N": "AJ1", "DQS0_P": "AH1",
    "DQS1_N": "AJ5", "DQS1_P": "AJ6",
    "DQS2_N": "AF8", "DQS2_P": "AE8",
    "DQS3_N": "AG11", "DQS3_P": "AF11",
    # data
    "DQ0": "AE2", "DQ1": "AG3", "DQ2": "AD1", "DQ3": "AF2",
    "DQ4": "AD2", "DQ5": "AH3", "DQ6": "AE1", "DQ7": "AF1",
    "DQ8": "AE3", "DQ9": "AH4", "DQ10": "AD4", "DQ11": "AG4",
    "DQ12": "AE4", "DQ13": "AG5", "DQ14": "AF3", "DQ15": "AJ4",
    "DQ16": "AD6", "DQ17": "AG8", "DQ18": "AF6", "DQ19": "AF7",
    "DQ20": "AD7", "DQ21": "AH8", "DQ22": "AE7", "DQ23": "AG6",
    "DQ24": "AE12", "DQ25": "AG9", "DQ26": "AH11", "DQ27": "AE9",
    "DQ28": "AH12", "DQ29": "AG10", "DQ30": "AF12", "DQ31": "AD10",
    # data mask
    "DM0": "AH2", "DM1": "AE5", "DM2": "AH7", "DM3": "AE10",
    # address (A14/A15/A16 are WE/CAS/RAS on x16 devices)
    "A0": "AN9", "A1": "AN6", "A2": "AN7", "A3": "AP5",
    "A4": "AK8", "A5": "AP7", "A6": "AM10", "A7": "AN8",
    "A8": "AK7", "A9": "AP10", "A10": "AM6", "A11": "AM8",
    "A12": "AP4", "A13": "AP8",
    "BA0": "AJ10", "BA1": "AP9",
    "RAS_B": "AP11", "CAS_B": "AP6", "WE_B": "AJ9",
    "ACT_B": "AM9", "CS_B": "AN4", "CKE": "AK10", "ODT": "AK9",
    "BG0": "AL10",
    "RST": "AM5",
    # differential clock
    "CLK_N": "AL5", "CLK_P": "AL6",
    # 200 MHz differential reference clock (manual 2.6.3)
    "REFCLK_P": "AL8", "REFCLK_N": "AL7",
}

# MIG top-level port -> manual net name
SINGLE = {
    "c0_ddr4_act_n": "ACT_B",
    "c0_ddr4_ck_t[0]": "CLK_P",
    "c0_ddr4_ck_c[0]": "CLK_N",
    "c0_ddr4_cke[0]": "CKE",
    "c0_ddr4_cs_n[0]": "CS_B",
    "c0_ddr4_odt[0]": "ODT",
    "c0_ddr4_reset_n": "RST",
    "c0_ddr4_bg[0]": "BG0",
    "c0_ddr4_ba[0]": "BA0",
    "c0_ddr4_ba[1]": "BA1",
    "c0_ddr4_adr[14]": "WE_B",
    "c0_ddr4_adr[15]": "CAS_B",
    "c0_ddr4_adr[16]": "RAS_B",
}
DIFF = {
    "c0_ddr4_dqs_t": "DQS{}_P",
    "c0_ddr4_dqs_c": "DQS{}_N",
}
for index in range(14):
    SINGLE[f"c0_ddr4_adr[{index}]"] = f"A{index}"
for index in range(32):
    SINGLE[f"c0_ddr4_dq[{index}]"] = f"DQ{index}"
for index in range(4):
    SINGLE[f"c0_ddr4_dm_dbi_n[{index}]"] = f"DM{index}"

HEADER = """# AXU9EGB PL DDR4 pin and I/O constraints for lm_head v3.1.
# Generated by experiments/board_v31_20261019/make_pin_xdc.py from the
# AXU9EGB user manual PL DDR4 table (2 x MT40A512M16LY-062E, 32-bit, 2 GiB,
# BANK64/65).  Do not edit by hand.
#
# PL_DDR4_RST is IO_L14N_T2L_N3_GC_64 AM5 (manual page 18).
"""


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    out = root / "constraints" / "lm_head_v31_ddr4_pins.xdc"
    lines = [HEADER]
    prefix = ""
    used = set()

    def emit(port: str, net: str, iostd: str) -> None:
        # make_bd_pins_external appends _0 to the BD cell pin name.
        if port.startswith('pl_ddr_refclk_'):
            name = port
        elif "[" in port:
            base, index = port.split("[", 1)
            name = f"{base}_0[{index}"
        else:
            name = f"{port}_0"
        pin = PINS[net]
        used.add(net)
        lines.append(f"set_property PACKAGE_PIN {pin} [get_ports {{{prefix}{name}}}]")
        lines.append(f"set_property IOSTANDARD {iostd} [get_ports {{{prefix}{name}}}]")
        if net == 'RST':
            lines.append(f"set_property DRIVE 8 [get_ports {{{prefix}{name}}}]")

    for port, net in sorted(SINGLE.items()):
        if net == 'RST':
            iostd = 'LVCMOS12'
        elif net.startswith("DQ") or net.startswith("DM"):
            iostd = "POD12_DCI"
        elif net.startswith("CLK"):
            iostd = "DIFF_SSTL12_DCI"
        else:
            iostd = "SSTL12_DCI"
        emit(port, net, iostd)
    for template, net_template in sorted(DIFF.items()):
        for index in range(4):
            emit(template + f"[{index}]", net_template.format(index), "DIFF_POD12_DCI")
    emit("pl_ddr_refclk_clk_p", "REFCLK_P", "DIFF_SSTL12")
    emit("pl_ddr_refclk_clk_n", "REFCLK_N", "DIFF_SSTL12")

    missing = sorted(set(PINS) - used)
    if missing:
        raise SystemExit(f"pin table entries not used: {missing}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {out} ({len(lines) - 1} constraint lines, {len(used)} nets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
